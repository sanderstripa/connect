//go:build windows

package main

import (
	"github.com/wailsapp/wails/v3/pkg/application"
	"github.com/wailsapp/wails/v3/pkg/events"
	"github.com/wailsapp/wails/v3/pkg/w32"
	"golang.org/x/sys/windows"
)

// Wails sets only ICON_BIG. Windows also uses ICON_SMALL for the taskbar.
// Load the same multi-size executable resource for both and let Windows own
// the shared icon handles for the lifetime of the application.
func configureWindowIcon(window application.Window) {
	loadImage := windows.NewLazySystemDLL("user32.dll").NewProc("LoadImageW")
	apply := func(_ *application.WindowEvent) {
		application.InvokeAsync(func() {
			hwnd := w32.HWND(uintptr(window.NativeWindow()))
			if hwnd == 0 { return }
			module := w32.GetModuleHandle("")
			for _, icon := range []struct { kind uintptr; width, height int }{
				{w32.ICON_SMALL, w32.GetSystemMetrics(w32.SM_CXSMICON), w32.GetSystemMetrics(w32.SM_CYSMICON)},
				{w32.ICON_BIG, w32.GetSystemMetrics(w32.SM_CXICON), w32.GetSystemMetrics(w32.SM_CYICON)},
			} {
				// Resource 3 is the executable icon group generated by Wails.
				// IMAGE_ICON = 1, LR_SHARED = 0x8000.
				handle, _, _ := loadImage.Call(uintptr(module), 3, 1, uintptr(icon.width), uintptr(icon.height), 0x8000)
				if handle != 0 { w32.SendMessage(hwnd, w32.WM_SETICON, icon.kind, handle) }
			}
		})
	}
	window.OnWindowEvent(events.Common.WindowRuntimeReady, apply)
	window.OnWindowEvent(events.Common.WindowDPIChanged, apply)
}
